def troop_abilities(unit):
    image=str(unit.get('unit_image') or unit.get('image_path') or '').replace('\\','/').casefold()
    name=str(unit.get('unit_name') or '').strip().casefold()
    return tuple(key for key,(images,names) in TROOPS.items() if name in names or any(image.endswith(path) for path in images))
