class TutorialProgress:
    def __init__(self, ideology):
        self.lessons = lessons_for(ideology)
        self.index = 0
        self.events = set()
        self.active = True

    @property
    def lesson(self):
        return self.lessons[self.index]

    @property
    def can_advance(self):
        return self.active and (not self.lesson.event or self.lesson.event in self.events)

    def record(self, event):
        if self.active:
            # An earlier turn does not fulfil the later, prepared-turn exercise.
            if event != 'turn_finished' or self.lesson.event == event:
                self.events.add(event)

    def next(self):
        if not self.can_advance:
            return False
        if self.index == len(self.lessons) - 1:
            self.active = False
        else:
            self.index += 1
        return True

    def back(self):
        if self.active:
            self.index = max(0, self.index - 1)

    def stop(self):
        self.active = False
