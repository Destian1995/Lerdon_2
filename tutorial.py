from dataclasses import dataclass
from weakref import WeakMethod


_event_handler = None


def set_event_handler(callback):
    global _event_handler
    _event_handler = WeakMethod(callback) if callback else None


def notify_event(event):
    callback = _event_handler() if _event_handler else None
    if callback:
        callback(event)


