def search_hint(detective):
    sites=detective.get('search_sites')
    if not sites:return ''
    site=sites[detective['search_answer']]
    return detective.get('search_hint') or SEARCH_HINTS.get(site,('Перечитайте показания свидетеля.',))[0]


def generate(conn,faction,cycle,rng=None):
    rng=rng or random
    chosen=[]
    for kind,pool in (('detective',DETECTIVE),('war',WARS)):
        used={r[0] for r in conn.execute('SELECT template FROM portal_quest_history WHERE faction=? AND kind=?',(faction,kind))}
        available=[x for x in pool if x[0] not in used]
        if not available:
            # Start a new shuffled deck, excluding the immediately previous story.
            last=conn.execute('SELECT template FROM portal_quest_history WHERE faction=? AND kind=? ORDER BY cycle DESC LIMIT 1',(faction,kind)).fetchone()
            conn.execute('DELETE FROM portal_quest_history WHERE faction=? AND kind=?',(faction,kind))
            available=[x for x in pool if not last or x[0]!=last[0]]
        seed=rng.choice(available)
        conn.execute('INSERT INTO portal_quest_history VALUES(?,?,?,?)',(faction,kind,seed[0],cycle))
        chosen.append(seed)
    d,w=chosen
    from otherworld_themes import CONFLICT_SIDES
    sides=list(CONFLICT_SIDES.get(faction,w[3]))
    places=list(range(2,8));rng.shuffle(places)
    war_places=list(range(2,8));rng.shuffle(war_places)
    scenario={'detective':{'id':d[0],'title':d[1],'premise':d[2],'witness':d[3],
                        'ledger':d[4],'solved':d[5],'cities':places[:3],
                        'suspects':rng.sample(NAMES,3),'tokens':list(rng.choice(CLUES)),
                        'search_sites':['Архив','Склад','Сад'], 'search_answer':rng.randrange(3)},
            'war':{'id':w[0],'title':w[1],'premise':w[2],'sides':sides,
                   'resource':w[4],'amount':w[5], 'embassy':war_places[0],
                   'supplies':war_places[1:3],'target':war_places[3]}}
    detective=scenario['detective']
    detective['search_hint']=rng.choice(SEARCH_HINTS[detective['search_sites'][detective['search_answer']]])
    return scenario


